import { launch, checker, BASE } from './_env.mjs'
const { browser: b, page: p, errs } = await launch()
const { ok, done } = checker('apex')
const dev = () => p.locator('.device')
const base = BASE

// ---------- APEX ----------
await p.goto(base + '#/apex'); await p.waitForSelector('.ax')
await p.getByLabel('Publicación').fill('Salida de prueba por el cañón'); await p.getByRole('button', { name: 'Publicar' }).click()
ok(await p.getByText('Salida de prueba por el cañón').count() === 1, 'Apex publica en el feed')
await p.getByRole('button', { name: 'Me gusta' }).first().click()
ok(await p.getByRole('button', { name: 'Me gusta' }).first().getAttribute('aria-pressed') === 'true', 'Apex me gusta')
await p.getByRole('tab', { name: 'Garaje' }).click()
await p.getByRole('button', { name: '+ Agregar' }).click()
await p.getByLabel('Marca').fill('Toyota'); await p.getByLabel('Modelo').fill('GR86'); await p.getByRole('button', { name: 'Guardar' }).click()
ok(await p.getByText('2020 Toyota GR86').count() === 1, 'Apex agrega vehículo')
await p.getByText('1994 Mazda MX-5').click()
await p.getByRole('button', { name: /Estimar ficha con IA/ }).click()
ok(await p.getByText('hp', { exact: true }).count() >= 1, 'Apex estima ficha')
await p.getByRole('button', { name: /Garaje/ }).first().click()
await p.getByRole('tab', { name: 'Pilotos' }).click(); await p.getByRole('button', { name: /Solicitudes/ }).click(); await p.getByRole('button', { name: 'Aceptar' }).click()
ok(await p.getByText('Ahora son amigos').count() === 1, 'Apex acepta solicitud')
// sesión GPS con pilotos en vivo
await p.getByRole('button', { name: 'Iniciar sesión GPS' }).click()
await p.getByRole('button', { name: /INICIAR SESIÓN/ }).click()
await p.getByRole('button', { name: /Pista/ }).click(); await p.getByRole('button', { name: /ARRANCAR/ }).click()
await p.waitForTimeout(1800)
ok(await p.getByText(/pilotos cercanos/).count() === 1, 'Apex muestra pilotos cercanos en vivo')
ok(await p.locator('[aria-label*="km/h"]').count() >= 2, 'Apex dibuja marcadores de amigos con velocidad')
await p.getByRole('button', { name: /Visible para amigos/ }).click()
ok(await p.getByText(/Ubicación oculta/).count() === 1, 'Apex alterna privacidad')
await p.getByRole('button', { name: /PAUSA/ }).click()
ok(await p.getByText('EN PAUSA').count() === 1, 'Apex pausa')
await p.getByRole('button', { name: /SEGUIR/ }).click(); await p.waitForTimeout(800)
await p.getByRole('button', { name: /FINALIZAR/ }).click()
ok(await p.getByText('Sesión terminada').count() === 1, 'Apex muestra resumen')
await p.getByRole('button', { name: /GUARDAR EN MI PERFIL/ }).click()
ok(await p.getByText(/Pista — 9\/11\/2026/).count() === 1, 'Apex guarda sesión en el perfil')
ok(!errs.length, 'sin errores de consola')
await b.close()
done()
