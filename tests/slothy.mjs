import { launch, checker, BASE } from './_env.mjs'
const { browser: b, page: p, errs } = await launch()
const { ok, done } = checker('slothy')
const dev = () => p.locator('.device')
await p.goto(BASE + '#/slothy'); await p.waitForSelector('.sl')
await p.getByRole('button', { name: 'Autorizo', exact: true }).click()
await p.getByRole('button', { name: /Hacer una cita/ }).click()
await p.getByRole('button', { name: /Corte de hombre/ }).click()
ok(await p.locator('.sl-day.cerrado').count() >= 3, 'domingos cerrados')
ok(await p.locator('.sl-day.lleno').count() >= 1, 'día lleno marcado')
await p.locator('.sl-day', { hasText: /^11$/ }).click()
await p.getByRole('button', { name: '2:00 p. m.', exact: true }).click()
await p.getByLabel('Tu nombre').fill('Paula Test'); await p.getByLabel('Tu celular').fill('3001112233')
await p.getByRole('button', { name: 'Continuar' }).click()
await p.getByRole('button', { name: 'Confirmar cita' }).click()
ok(await p.getByText(/Tu cita de Corte de hombre quedó el mié 11 nov a las 2:00 p. m./).count() === 1, 'confirmación en el chat')
await p.getByRole('button', { name: 'Volver al inicio' }).click()
await p.getByRole('button', { name: /Mis citas/ }).click()
ok(await p.getByText('Corte de hombre').count() >= 1, 'Mis citas muestra la cita')
await p.getByRole('button', { name: 'Soy el negocio' }).click()
ok(await p.getByText('Nuevas por el chat').count() === 1 && await p.locator('.sl-stat', { hasText: 'Nuevas por el chat' }).locator('b').innerText() === '1', 'el resumen cuenta la cita hecha por chat')
await p.getByRole('button', { name: 'Agenda', exact: true }).click()
await p.locator('.sl-ev.chat').first().click()
await p.getByRole('button', { name: 'Asistió' }).click()
await p.getByRole('button', { name: 'Ingresos', exact: true }).click()
ok(await p.getByText('$30.000').count() >= 1, 'ingresos reflejan la cita atendida')
await p.getByRole('button', { name: 'Agenda', exact: true }).click()
await p.getByRole('button', { name: '+ Nueva cita' }).click()
await p.getByPlaceholder('Nombre completo').fill('Cliente Panel'); await p.getByRole('button', { name: 'Guardar cita' }).click()
ok(await p.locator('.sl-ev', { hasText: 'Cliente' }).count() >= 1, 'nueva cita desde el panel aparece en la agenda')
await p.locator('.sl-switch').getByRole('button', { name: 'Cambiar tema' }).click()
ok(!errs.length, 'sin errores de consola')
await b.close()
done()
